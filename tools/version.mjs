/**
 * Synchronizes major.minor.patch version metadata across package.json, package-lock.json,
 * extension/manifest.json, root installer artifacts, and CHANGELOG.txt.
 *
 * Usage:
 *   npm run version:patch   # bumps 0.2.0 -> 0.2.1 (leaves tree uncommitted to edit CHANGELOG.txt)
 *   npm run version:minor   # bumps 0.2.0 -> 0.3.0
 *   npm run version:major   # bumps 0.2.0 -> 1.0.0
 *   npm version minor       # standard npm lifecycle bump + auto-stages synced artifacts
 */
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
export const SEMVER_RE = /^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)(?:-[0-9A-Za-z.-]+)?$/;

export function bumpSemver(current, releaseType) {
    const match = /^(\d+)\.(\d+)\.(\d+)/.exec(String(current).trim());
    assert.ok(match, `Invalid current SemVer version: ${current}`);
    const major = Number(match[1]);
    const minor = Number(match[2]);
    const patch = Number(match[3]);
    if (releaseType === 'major') return `${major + 1}.0.0`;
    if (releaseType === 'minor') return `${major}.${minor + 1}.0`;
    if (releaseType === 'patch') return `${major}.${minor}.${patch + 1}`;
    assert.ok(SEMVER_RE.test(releaseType), `Expected major, minor, patch, or explicit SemVer, got: ${releaseType}`);
    return releaseType;
}

export function ensureChangelogEntry(changelogText, version, dateString = new Date().toISOString().slice(0, 10)) {
    const escaped = version.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    const headingRe = new RegExp(`^Version\\s+${escaped}\\b`, 'm');
    if (headingRe.test(changelogText)) return changelogText;

    const headerMatch = /^LPC Companion — What's New\r?\n=+\r?\n+/m.exec(changelogText);
    const titleLine = `Version ${version} (${dateString})`;
    const underline = '-'.repeat(titleLine.length);
    const stub = `${titleLine}\n${underline}\n- Describe user-visible highlights and improvements here.\n\n`;

    if (headerMatch) {
        const insertAt = headerMatch.index + headerMatch[0].length;
        return changelogText.slice(0, insertAt) + stub + changelogText.slice(insertAt);
    }
    return `LPC Companion — What's New\n==========================\n\n${stub}${changelogText}`;
}

export function buildReleaseInfoModule({ displayName = 'LPC Companion', version, changelogText }) {
    return [
        '/** Generated by tools/version.mjs from extension/manifest.json and CHANGELOG.txt. */',
        `export const EXTENSION_DISPLAY_NAME = ${JSON.stringify(displayName)};`,
        `export const EXTENSION_VERSION = ${JSON.stringify(version)};`,
        `export const CHANGELOG_TEXT = ${JSON.stringify(changelogText)};`,
        '',
        'export function parseChangelog(text) {',
        '    const entries = [];',
        '    let current = null;',
        '    let group = null;',
        '    for (const rawLine of String(text ?? \'\').split(/\\r?\\n/)) {',
        '        const line = rawLine.trim();',
        '        if (!line || /^[=\\-]{3,}$/.test(line) || line.startsWith(\'LPC Companion —\')) continue;',
        '        const versionMatch = /^Version\\s+([^\\s]+)(?:\\s*\\(([^)]+)\\))?$/.exec(line);',
        '        if (versionMatch) {',
        '            current = {',
        '                version: versionMatch[1],',
        '                date: versionMatch[2] ?? \'\',',
        '                groups: [],',
        '            };',
        '            entries.push(current);',
        '            group = null;',
        '            continue;',
        '        }',
        '        if (!current) continue;',
        '        if (line.startsWith(\'- \')) {',
        '            if (!group) {',
        '                group = { heading: \'\', items: [] };',
        '                current.groups.push(group);',
        '            }',
        '            group.items.push(line.slice(2).trim());',
        '        } else if (line.endsWith(\':\')) {',
        '            group = { heading: line.slice(0, -1).trim(), items: [] };',
        '            current.groups.push(group);',
        '        }',
        '    }',
        '    return entries.map(entry => Object.freeze({',
        '        version: entry.version,',
        '        date: entry.date,',
        '        groups: Object.freeze(entry.groups.filter(g => g.items.length > 0).map(g => Object.freeze({',
        '            heading: g.heading,',
        '            items: Object.freeze(g.items),',
        '        }))),',
        '    }));',
        '}',
        '',
        'export const CHANGELOG_ENTRIES = Object.freeze(parseChangelog(CHANGELOG_TEXT));',
        '',
    ].join('\n');
}

export async function syncReleaseInfoModule(rootDir = ROOT) {
    const extManifest = JSON.parse(await readFile(path.join(rootDir, 'extension/manifest.json'), 'utf8'));
    const changelogText = await readFile(path.join(rootDir, 'CHANGELOG.txt'), 'utf8');
    const outPath = path.join(rootDir, 'src/catalog/release-info.mjs');
    const nextSource = buildReleaseInfoModule({
        displayName: extManifest.display_name ?? 'LPC Companion',
        version: extManifest.version,
        changelogText,
    });
    let existing = null;
    try {
        existing = await readFile(outPath, 'utf8');
    } catch (error) {
        if (error.code !== 'ENOENT') throw error;
    }
    if (existing !== nextSource) {
        await mkdir(path.dirname(outPath), { recursive: true });
        await writeFile(outPath, nextSource);
    }
    return outPath;
}

export async function syncVersionFiles({
    rootDir = ROOT,
    targetVersion = null,
    dateString = new Date().toISOString().slice(0, 10),
    rebuildInstaller = false,
} = {}) {
    const pkgPath = path.join(rootDir, 'package.json');
    const lockPath = path.join(rootDir, 'package-lock.json');
    const extManifestPath = path.join(rootDir, 'extension/manifest.json');
    const changelogPath = path.join(rootDir, 'CHANGELOG.txt');

    const pkg = JSON.parse(await readFile(pkgPath, 'utf8'));
    const nextVersion = targetVersion ? bumpSemver(pkg.version, targetVersion) : pkg.version;
    assert.ok(SEMVER_RE.test(nextVersion), `Invalid target SemVer: ${nextVersion}`);

    if (pkg.version !== nextVersion) {
        pkg.version = nextVersion;
        await writeFile(pkgPath, `${JSON.stringify(pkg, null, 2)}\n`);
    }

    const lock = JSON.parse(await readFile(lockPath, 'utf8'));
    let lockChanged = false;
    if (lock.version !== nextVersion) {
        lock.version = nextVersion;
        lockChanged = true;
    }
    if (lock.packages?.[''] && lock.packages[''].version !== nextVersion) {
        lock.packages[''].version = nextVersion;
        lockChanged = true;
    }
    if (lockChanged) {
        await writeFile(lockPath, `${JSON.stringify(lock, null, 2)}\n`);
    }

    const extManifest = JSON.parse(await readFile(extManifestPath, 'utf8'));
    if (extManifest.version !== nextVersion || extManifest.display_name !== 'LPC Companion') {
        extManifest.display_name = 'LPC Companion';
        extManifest.version = nextVersion;
        await writeFile(extManifestPath, `${JSON.stringify(extManifest, null, 2)}\n`);
    }

    let existingChangelog = '';
    try {
        existingChangelog = await readFile(changelogPath, 'utf8');
    } catch (error) {
        if (error.code !== 'ENOENT') throw error;
    }
    const nextChangelog = ensureChangelogEntry(existingChangelog, nextVersion, dateString);
    if (nextChangelog !== existingChangelog) {
        await writeFile(changelogPath, nextChangelog);
    }

    await syncReleaseInfoModule(rootDir);

    if (rebuildInstaller) {
        execFileSync(process.execPath, [path.join(rootDir, 'tools/prepare-install.mjs')], {
            cwd: rootDir,
            stdio: 'inherit',
        });
        execFileSync(process.execPath, [path.join(rootDir, 'tools/check-install.mjs')], {
            cwd: rootDir,
            stdio: 'inherit',
        });
    }

    return { version: nextVersion };
}

if (path.resolve(process.argv[1] ?? '') === fileURLToPath(import.meta.url)) {
    const args = process.argv.slice(2);
    const npmLifecycle = args.includes('--npm-lifecycle');
    const skipBuild = args.includes('--skip-build');
    const positional = args.find(arg => !arg.startsWith('--')) ?? null;

    syncVersionFiles({
        targetVersion: npmLifecycle ? null : positional,
        rebuildInstaller: !skipBuild,
    }).then(({ version }) => {
        if (npmLifecycle && process.env.npm_config_git_tag_version !== 'false') {
            execFileSync('git', [
                'add',
                'CHANGELOG.txt',
                'extension/manifest.json',
                'src/catalog/release-info.mjs',
                'manifest.json',
                'lpc-runtime.mjs',
                'install-build.json',
            ], { cwd: ROOT, stdio: 'inherit' });
        }
        console.log(`Synchronized LPC Companion version ${version}.`);
    }).catch(error => {
        console.error(error.stack ?? error.message);
        process.exitCode = 1;
    });
}
